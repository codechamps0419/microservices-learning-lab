package com.example.order.grpc;

import com.example.order.dto.ProductClientResponse;
import com.example.order.exception.ProductNotFoundException;
import com.example.order.exception.ProductServiceException;
import com.example.order.exception.ProductServiceUnavailableException;
import io.grpc.StatusRuntimeException;
import lombok.extern.slf4j.Slf4j;
import net.devh.boot.grpc.client.inject.GrpcClient;
import org.springframework.stereotype.Component;

import java.math.BigDecimal;
import java.util.UUID;

/*
 * gRPC client for product-service.
 *
 * =========================================================================
 * HOW gRPC CLIENT WORKS
 * =========================================================================
 *
 * grpc-spring-boot-starter generates a blocking stub from the .proto file.
 * A blocking stub means the call blocks the current thread until the server
 * responds — same behaviour as RestClient. This is called a unary RPC.
 *
 * @GrpcClient("product-service") tells the starter to:
 *   1. Read the server address from application.yml:
 *      grpc.client.product-service.address=static://localhost:9091
 *   2. Create a managed channel (connection pool) to that address
 *   3. Inject a ProductServiceGrpc.ProductServiceBlockingStub into this field
 *
 * The stub is auto-generated by the Maven protobuf plugin from product.proto.
 * You never write the stub — you only write this wrapper class.
 *
 * =========================================================================
 * BLOCKING STUB vs ASYNC STUB vs FUTURE STUB
 * =========================================================================
 *
 *   Stub type       Returns         Use when
 *   --------------  --------------  ----------------------------------------
 *   BlockingStub    Direct value    Simple synchronous calls (this project)
 *   FutureStub      ListenableFuture  Guava-based async
 *   AsyncStub       StreamObserver  Streaming RPCs, reactive pipelines
 *
 * BlockingStub is the simplest and matches the synchronous style of the
 * rest of this project (RestClient is also synchronous).
 *
 * =========================================================================
 * ERROR HANDLING — StatusRuntimeException
 * =========================================================================
 *
 * When the gRPC server calls responseObserver.onError(), the client receives
 * a StatusRuntimeException. The status code tells you what went wrong:
 *
 *   Status.Code.NOT_FOUND       → ProductNotFoundException
 *   Status.Code.UNAVAILABLE     → ProductServiceUnavailableException
 *   Status.Code.INVALID_ARGUMENT → ProductServiceException (bad request)
 *   anything else               → ProductServiceException (unexpected)
 *
 * Same rule as RestClient: StatusRuntimeException must never escape this class.
 * OrderService works with typed business exceptions only.
 */
@Slf4j
@Component
public class ProductGrpcClient {

    /*
     * @GrpcClient injects the auto-generated blocking stub.
     * "product-service" matches the key in application.yml:
     *   grpc.client.product-service.address=...
     *
     * The stub handles connection management, retries, and serialisation.
     * You just call stub.getProduct(request).
     */
    @GrpcClient("product-service")
    private ProductServiceGrpc.ProductServiceBlockingStub stub;

    /*
     * Calls rpc GetProduct on product-service via gRPC.
     *
     * Returns the same ProductClientResponse DTO used by the REST client.
     * This means OrderService and controllers can use either client
     * interchangeably — the return type is identical.
     */
    public ProductClientResponse getProduct(UUID productId) {
        log.info("gRPC call --> product-service getProduct productId={}", productId);

        GetProductRequest request = GetProductRequest.newBuilder()
                .setProductId(productId.toString())
                .build();

        try {
            GetProductResponse response = stub.getProduct(request);

            // Map protobuf response to the same DTO the REST client returns.
            // price was serialised as a string — parse back to BigDecimal.
            ProductClientResponse result = new ProductClientResponse();
            result.setId(UUID.fromString(response.getId()));
            result.setName(response.getName());
            result.setPrice(new BigDecimal(response.getPrice()));
            result.setStatus(response.getStatus());

            log.info("gRPC getProduct success for productId={}", productId);
            return result;

        } catch (StatusRuntimeException e) {
            // Translate gRPC status codes into the same typed exceptions
            // that ProductClient (REST) throws. Callers see no difference.
            switch (e.getStatus().getCode()) {
                case NOT_FOUND -> {
                    log.warn("gRPC getProduct: product not found productId={}", productId);
                    throw new ProductNotFoundException(productId);
                }
                case UNAVAILABLE -> {
                    log.error("gRPC getProduct: product-service unavailable productId={}", productId);
                    throw new ProductServiceUnavailableException(
                            "product-service is currently unavailable via gRPC.", e);
                }
                default -> {
                    log.error("gRPC getProduct: unexpected status={} productId={}",
                            e.getStatus().getCode(), productId);
                    throw new ProductServiceException(
                            "gRPC call to product-service failed: " + e.getStatus().getDescription());
                }
            }
        }
    }
}
